/**
 * KPI Dictionary (BRD 120-124).
 *
 * Every KPI is defined once, here. Dashboards, reports and exports read these
 * definitions and call the matching function in `./metrics.ts` — no dashboard
 * recomputes a formula of its own.
 */

export type KpiScope =
  | 'portfolio'
  | 'region'
  | 'city'
  | 'district'
  | 'property'
  | 'building'
  | 'unit'
  | 'leasing'
  | 'collections'
  | 'maintenance'
  | 'marketing';

export type KpiFormat = 'currency' | 'percent' | 'number' | 'days' | 'ratio' | 'area';

