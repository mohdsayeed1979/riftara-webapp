export const KPI_BY_KEY = new Map(KPI_DICTIONARY.map((kpi) => [kpi.key, kpi]));

/** Resolves a value to its green/amber/red band (BRD 75). */
export function kpiBand(
  key: string,
  value: number,
): 'green' | 'amber' | 'red' | 'none' {
  const kpi = KPI_BY_KEY.get(key);
  if (!kpi?.thresholds) return 'none';
  const { green, amber } = kpi.thresholds;
  if (kpi.higherIsBetter) {
    if (value >= green) return 'green';
    if (value >= amber) return 'amber';
    return 'red';
  }
  if (value <= green) return 'green';
  if (value <= amber) return 'amber';
  return 'red';
}
